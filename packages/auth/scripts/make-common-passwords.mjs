// Writes src/common-passwords.ts: the ten thousand most used passwords of eight characters or more, lowercased and
// in the order people use them, from the UK NCSC's list of the 100,000 most seen in breaches as SecLists publishes it
// (MIT). Run with `node scripts/make-common-passwords.mjs` from packages/auth, then format the file.
import { writeFileSync } from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt";
/** The farm's shortest password, and Better Auth's longest: nothing outside them can be chosen, so none is listed. */
const SHORTEST = 8;
const LONGEST = 128;
/** How many are kept: ASVS 6.2.4 asks for at least three thousand. */
const KEPT = 10_000;

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Could not fetch the list: ${response.status}`);
}
const kept = [];
const seen = new Set();
const text = await response.text();
for (const line of text.split("\n")) {
  const word = line.replace(/\r$/u, "");
  const lower = word.toLowerCase();
  if (word.length < SHORTEST || word.length > LONGEST || seen.has(lower)) {
    continue;
  }
  seen.add(lower);
  kept.push(lower);
  if (kept.length >= KEPT) {
    break;
  }
}
const body = kept.join("\n");
if (body.includes("`") || body.includes("${") || body.includes("\\")) {
  throw new Error("A listed password would break the template literal");
}

writeFileSync(
  new URL("../src/common-passwords.ts", import.meta.url),
  `/**
 * The passwords too common to be one (ASVS 6.2.4): the ten thousand most used of eight characters or more, lowercased,
 * in the order people use them. Taken from the UK National Cyber Security Centre's list of the 100,000 passwords most
 * seen in breaches, as SecLists publishes it
 * (\`Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt\`, MIT), filtered to the farm's shortest length.
 *
 * An Investor signs in with their phone number, which is no secret, and no second factor — so the password is the one
 * secret there is, and \`12345678\` is not one. Generated by \`scripts/make-common-passwords.mjs\`; not edited by hand.
 */
const LISTED = \`${body}\`;

let listed: Set<string> | null = null;

/** Whether a password is one of the common ones, whatever its capitals. */
export const isCommonPassword = (password: string): boolean => {
  listed ??= new Set(LISTED.split("\\n"));
  return listed.has(password.toLowerCase());
};
`
);
